    #[test]
    fn fills_slots_in_any_order() {
        assert_eq!(
            fill("{missing} not in {path}", &[("path", "C:\\g"), ("missing", "x.json")]),
            "x.json not in C:\\g"
        );
    }

    #[test]
    fn picks_language_by_primary_tag() {
        assert!(std::ptr::eq(pick("it-IT"), &IT));
        assert!(std::ptr::eq(pick("pt_BR"), &PT));
        assert!(std::ptr::eq(pick("ru"), &RU));
        assert!(std::ptr::eq(pick("de-DE"), &EN));
        assert!(std::ptr::eq(pick(""), &EN));
    }
