pub fn get() -> &'static Strings {
    if let Ok(tag) = std::env::var("SND_INSTALLER_LANG") {
        return pick(&tag);
    }
    let locale = sys_locale::get_locale().unwrap_or_default();
    pick(&locale)
}

/// Map a BCP-47-ish tag ("es", "pt-BR", "fr_FR") to a language table.
pub fn pick(tag: &str) -> &'static Strings {
    let tag = tag.trim().to_lowercase().replace('_', "-");
    let primary = tag.split('-').next().unwrap_or("");
    match primary {
        "es" => &ES,
        "fr" => &FR,
        "it" => &IT,
        "pt" => &PT,
        "ru" => &RU,
        _ => &EN,
    }
}

/// Fill {name}-style slots. Slots may appear in any order in a translation.
pub fn fill(template: &str, args: &[(&str, &str)]) -> String {
    let mut out = template.to_string();
    for (key, value) in args {
        out = out.replace(&format!("{{{key}}}"), value);
    }
    out
}

